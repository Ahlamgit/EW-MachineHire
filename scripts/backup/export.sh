#!/usr/bin/env bash
# EW Machine Hire — scheduled logical export (Supabase Free / zero new fees).
# Run on an existing company computer. Do not purchase backup SaaS.
# Secrets: load from backup.env (gitignored). Never commit dumps.
#
# Usage:
#   export EWM_BACKUP_ROOT=/path/to/backups
#   export SUPABASE_DB_URL='postgresql://...'
#   ./scripts/backup/export.sh
# Or: source scripts/backup/backup.env then run this script.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

if [[ -f "${SCRIPT_DIR}/backup.env" ]]; then
  # shellcheck disable=SC1091
  set -a
  # Prefer explicit path; do not print values
  source "${SCRIPT_DIR}/backup.env"
  set +a
fi

: "${SUPABASE_DB_URL:?Set SUPABASE_DB_URL (see scripts/backup/backup.env.example)}"
: "${EWM_BACKUP_ROOT:?Set EWM_BACKUP_ROOT to a directory outside git}"

PROJECT_LABEL="${EWM_BACKUP_PROJECT:-supabase}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
DOW="$(date -u +%u)" # 1=Mon .. 7=Sun (ISO); weekly copy on Sunday (7)
LOG_DIR="${EWM_BACKUP_LOG_DIR:-${EWM_BACKUP_ROOT}/logs}"
DAILY_DIR="${EWM_BACKUP_ROOT}/daily"
WEEKLY_DIR="${EWM_BACKUP_ROOT}/weekly"
RUN_DIR="${DAILY_DIR}/${STAMP}-${PROJECT_LABEL}"
FAILURE_FLAG="${LOG_DIR}/LAST_FAILURE.txt"
SUCCESS_FLAG="${LOG_DIR}/LAST_SUCCESS.txt"
LOG_FILE="${LOG_DIR}/export-${STAMP}.log"

mkdir -p "${RUN_DIR}" "${WEEKLY_DIR}" "${LOG_DIR}"

log() {
  local msg="$1"
  printf '%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "${msg}" | tee -a "${LOG_FILE}"
}

fail() {
  local msg="$1"
  log "FAILURE: ${msg}"
  {
    echo "timestamp_utc=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "project=${PROJECT_LABEL}"
    echo "run_dir=${RUN_DIR}"
    echo "message=${msg}"
    echo "log=${LOG_FILE}"
  } >"${FAILURE_FLAG}"
  if [[ -n "${EWM_BACKUP_FAILURE_HOOK:-}" ]]; then
    # Local hook only (e.g. write to a shared ops folder). No paid SaaS.
    # shellcheck disable=SC2086
    eval ${EWM_BACKUP_FAILURE_HOOK} || true
  fi
  exit 1
}

command -v pg_dump >/dev/null 2>&1 || fail "pg_dump not found — install PostgreSQL client tools"
command -v psql >/dev/null 2>&1 || fail "psql not found — install PostgreSQL client tools"

log "Starting export project=${PROJECT_LABEL} run_dir=${RUN_DIR}"

# --- 1. Full logical dump (custom format) ---
DUMP_FILE="${RUN_DIR}/database.dump"
log "pg_dump → database.dump (custom format)"
if ! pg_dump "${SUPABASE_DB_URL}" \
  --format=custom \
  --no-owner \
  --no-acl \
  --file="${DUMP_FILE}"; then
  fail "pg_dump failed"
fi

DUMP_BYTES="$(wc -c <"${DUMP_FILE}" | tr -d ' ')"
if [[ "${DUMP_BYTES}" -lt 1024 ]]; then
  fail "dump file suspiciously small (${DUMP_BYTES} bytes)"
fi
log "database.dump size_bytes=${DUMP_BYTES}"

# --- 2. Roles inventory (business RBAC tables if present) ---
ROLES_SQL="${RUN_DIR}/roles-inventory.sql"
ROLES_QUERY="${RUN_DIR}/.roles-inventory-query.sql"
log "Exporting roles / permissions inventory SQL"
cat >"${ROLES_QUERY}" <<'SQL'
-- EW Machine Hire roles inventory (generated by scripts/backup/export.sh)
-- Counts
SELECT 'roles_count' AS metric, count(*)::text AS value FROM public.roles
UNION ALL
SELECT 'permissions_count', count(*)::text FROM public.permissions
UNION ALL
SELECT 'user_roles_count', count(*)::text FROM public.user_roles;

-- roles
SELECT key, name, description FROM public.roles ORDER BY key;

-- role_permissions
SELECT r.key AS role_key, p.key AS permission_key
FROM public.role_permissions rp
JOIN public.roles r ON r.id = rp.role_id
JOIN public.permissions p ON p.id = rp.permission_id
ORDER BY 1, 2;

-- user_roles (emails from profiles when available)
SELECT p.email, r.key AS role_key
FROM public.user_roles ur
JOIN public.profiles p ON p.id = ur.user_id
JOIN public.roles r ON r.id = ur.role_id
ORDER BY 1, 2;
SQL
if ! psql "${SUPABASE_DB_URL}" -v ON_ERROR_STOP=0 -f "${ROLES_QUERY}" >"${ROLES_SQL}" 2>>"${LOG_FILE}"; then
  log "WARN: roles inventory query returned non-zero (tables may not exist yet)"
  echo "-- roles inventory unavailable" >"${ROLES_SQL}"
fi
rm -f "${ROLES_QUERY}"

# --- 3. Auth users summary (auth schema — no passwords) ---
AUTH_SUMMARY="${RUN_DIR}/auth-users-summary.csv"
log "Exporting auth.users summary (id,email,created_at,last_sign_in — no secrets)"
if ! psql "${SUPABASE_DB_URL}" -v ON_ERROR_STOP=0 -c "\copy (
  SELECT id, email, created_at, last_sign_in_at, email_confirmed_at
  FROM auth.users
  ORDER BY created_at
) TO STDOUT WITH CSV HEADER" >"${AUTH_SUMMARY}" 2>>"${LOG_FILE}"; then
  log "WARN: auth.users summary failed (insufficient privileges or schema missing)"
  echo "id,email,note" >"${AUTH_SUMMARY}"
  echo ",,auth summary unavailable — document Auth users from Dashboard" >>"${AUTH_SUMMARY}"
fi

# --- 4. Migrations inventory (git + applied, if accessible) ---
MIG_DIR="${RUN_DIR}/migrations-inventory"
mkdir -p "${MIG_DIR}"
log "Copying migration file inventory from repo"
if [[ -d "${REPO_ROOT}/supabase/migrations" ]]; then
  find "${REPO_ROOT}/supabase/migrations" -type f -name '*.sql' | sort >"${MIG_DIR}/repo-migration-files.txt"
  # Checksums for integrity of the inventory list
  if command -v sha256sum >/dev/null 2>&1; then
    (
      cd "${REPO_ROOT}/supabase/migrations"
      find . -type f -name '*.sql' -print0 | sort -z | xargs -0 sha256sum
    ) >"${MIG_DIR}/repo-migration-sha256.txt" 2>/dev/null || true
  fi
else
  echo "(no supabase/migrations directory)" >"${MIG_DIR}/repo-migration-files.txt"
fi

APPLIED="${MIG_DIR}/applied-schema-migrations.txt"
log "Listing supabase_migrations.schema_migrations if present"
psql "${SUPABASE_DB_URL}" -v ON_ERROR_STOP=0 -At -c \
  "SELECT version || CASE WHEN COALESCE(name,'') <> '' THEN ' ' || name ELSE '' END
   FROM supabase_migrations.schema_migrations
   ORDER BY version;" \
  >"${APPLIED}" 2>>"${LOG_FILE}" || echo "(could not read supabase_migrations.schema_migrations)" >"${APPLIED}"

# --- 5. Auth + config documentation checklist (operator fills offline) ---
CONFIG_CHECKLIST="${RUN_DIR}/AUTH_CONFIG_CHECKLIST.md"
cat >"${CONFIG_CHECKLIST}" <<'EOF'
# Auth & project config checklist (fill on each backup day)

This file is a **placeholder checklist**. Values are **not** pulled automatically from the Dashboard.
Store completed copies in the company ops vault (not in git).

## Supabase Auth (Dashboard → Authentication)

- [ ] Site URL: ________________________________
- [ ] Redirect URLs (list): ____________________
- [ ] Email provider enabled: yes / no
- [ ] Custom SMTP enabled: yes / no
- [ ] SMTP host (no password): _________________
- [ ] SMTP sender email: _______________________
- [ ] Auth rate limit email/hour (if known): ____
- [ ] Screenshot of Auth URL settings saved to ops vault: yes / no

## Project

- [ ] Project ref: _____________________________
- [ ] Region: __________________________________
- [ ] Free tier: yes / no
- [ ] Netlify / host `NEXT_PUBLIC_APP_URL`: _____
- [ ] Env var names present on host (values NOT written here): URL, anon/publishable, service role (server)

## Notes

Date (UTC): 
Operator: 
EOF
log "Wrote AUTH_CONFIG_CHECKLIST.md (operator must complete offline)"

# --- 6. Manifest ---
MANIFEST="${RUN_DIR}/MANIFEST.txt"
{
  echo "ewm_backup_manifest_version=1"
  echo "timestamp_utc=${STAMP}"
  echo "project=${PROJECT_LABEL}"
  echo "database_dump=database.dump"
  echo "database_dump_bytes=${DUMP_BYTES}"
  echo "roles_inventory=roles-inventory.sql"
  echo "auth_users_summary=auth-users-summary.csv"
  echo "migrations_inventory=migrations-inventory/"
  echo "auth_config_checklist=AUTH_CONFIG_CHECKLIST.md"
  echo "repo_root_hint=${REPO_ROOT}"
  echo "not_covered=see docs/BACKUP_RECOVERY.md section What is not covered"
} >"${MANIFEST}"

# --- 7. Weekly promotion (Sunday UTC) ---
if [[ "${DOW}" == "7" ]]; then
  WEEKLY_COPY="${WEEKLY_DIR}/${STAMP}-${PROJECT_LABEL}"
  log "Promoting daily run to weekly → ${WEEKLY_COPY}"
  rm -rf "${WEEKLY_COPY}"
  cp -a "${RUN_DIR}" "${WEEKLY_COPY}"
fi

# --- 8. Prune ---
if [[ -x "${SCRIPT_DIR}/prune.sh" ]]; then
  log "Running prune.sh"
  EWM_BACKUP_ROOT="${EWM_BACKUP_ROOT}" \
    EWM_BACKUP_RETENTION_DAILY="${EWM_BACKUP_RETENTION_DAILY:-7}" \
    EWM_BACKUP_RETENTION_WEEKLY="${EWM_BACKUP_RETENTION_WEEKLY:-4}" \
    "${SCRIPT_DIR}/prune.sh" || log "WARN: prune reported issues"
else
  log "WARN: prune.sh missing or not executable"
fi

{
  echo "timestamp_utc=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "project=${PROJECT_LABEL}"
  echo "run_dir=${RUN_DIR}"
  echo "dump_bytes=${DUMP_BYTES}"
  echo "log=${LOG_FILE}"
} >"${SUCCESS_FLAG}"
rm -f "${FAILURE_FLAG}"

log "SUCCESS export complete"
echo "${RUN_DIR}"
